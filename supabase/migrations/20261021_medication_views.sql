CREATE TABLE IF NOT EXISTS public.medication_views (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  medication_id bigint NOT NULL REFERENCES public.medications(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS medication_views_created_at_idx
  ON public.medication_views (created_at DESC);

CREATE INDEX IF NOT EXISTS medication_views_medication_created_at_idx
  ON public.medication_views (medication_id, created_at DESC);

ALTER TABLE public.medication_views ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT ON TABLE public.medication_views TO authenticated;

DROP POLICY IF EXISTS medication_views_authenticated_select ON public.medication_views;
CREATE POLICY medication_views_authenticated_select
  ON public.medication_views
  FOR SELECT
  TO authenticated
  USING (true);

DROP POLICY IF EXISTS medication_views_authenticated_insert ON public.medication_views;
CREATE POLICY medication_views_authenticated_insert
  ON public.medication_views
  FOR INSERT
  TO authenticated
  WITH CHECK (true);
